import { cpSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';
import { buildDossier } from './vendor/makefun-game.ts';
const root=dirname(fileURLToPath(import.meta.url));
const out=resolve(process.env.MAKEFUN_OUTPUT_DIR||'/output');
const dossierCaps={text_max_bytes:163840,screenshots:{max:4,max_bytes:262144},game_max_files:993,game_max_bytes:50331648};
mkdirSync(out,{recursive:true});mkdirSync(join(out,'screenshots'),{recursive:true});
cpSync(join(root,'game'),join(out,'game'),{recursive:true});
cpSync(join(root,'screenshots'),join(out,'screenshots'),{recursive:true});
writeFileSync(join(out,'dossier.json'),buildDossier(out,dossierCaps));
